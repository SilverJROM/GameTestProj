// Precomputes the walking graph and the monster patrol cells so the Worker never spends 100 to 250 ms of CPU on its
// first click or first patrol tick. Writes src/rules/precomputed.generated.ts only when the content changed (see
// build-client.mjs for why). Run by `wrangler dev`/`deploy` as part of the build command, or by `npm run build:precompute`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'rules', 'precomputed.generated.ts');

const bundled = await esbuild.build({
  stdin: {
    contents: `
      import { buildFixedGraph } from './src/rules/route';
      import { packZoneCells } from './src/rules/radish';
      export const graph = buildFixedGraph();
      export const cells = { green: packZoneCells('green'), grey: packZoneCells('grey'), cemetery: packZoneCells('cemetery'), town: packZoneCells('town') };
    `,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
  logLevel: 'silent',
  // Build from the sources only, never from the file this script writes.
  plugins: [
    {
      name: 'empty-generated',
      setup(build) {
        build.onResolve({ filter: /precomputed\.generated$/ }, () => ({ path: 'empty', namespace: 'empty' }));
        build.onLoad({ filter: /.*/, namespace: 'empty' }, () => ({
          contents: 'export const routeGraphData = null; export const patrolCellsData = null;',
          loader: 'js',
        }));
      },
    },
  ],
});
const mod = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);

const text =
  '// Generated by scripts/build-precompute.mjs. Do not edit by hand.\n' +
  `export const routeGraphData: { nodes: [number, number][]; links: number[][] } | null = ${JSON.stringify({ nodes: mod.graph.nodes, links: mod.graph.links })};\n` +
  `export const patrolCellsData: Record<string, { spots: [number, number][]; cells: number[][] }> | null = ${JSON.stringify(mod.cells)};\n`;

let previous = '';
try {
  previous = readFileSync(out, 'utf8');
} catch {
  previous = '';
}
if (previous !== text) writeFileSync(out, text);
