// Bundles src/client/index.html and src/client/client.js into src/client/shell.generated.ts,
// so the Worker can return both as strings from / and /client.js. Wrangler runs this as its
// build command (wrangler.jsonc); npm run build:client runs it by hand. Pictures are not
// touched here: they stay on the assets directory.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const clientDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'client');
const peachHtml = readFileSync(join(clientDir, 'index.html'), 'utf8');
// One script for the browser: client.js plus the papaya view, click peel, and lemon socket.
const bundled = await esbuild.build({
  entryPoints: [join(clientDir, 'client.js')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  write: false,
  logLevel: 'silent',
});
const mangoJs = bundled.outputFiles[0]?.text ?? '';
if (!mangoJs.includes('/api/signin') || !mangoJs.includes('/api/avatars') || !mangoJs.includes('/api/play')) {
  throw new Error('client bundle is missing the account screens');
}
if (mangoJs.includes('/api/login')) {
  throw new Error('client bundle still posts /api/login');
}

const banner = '// Generated by scripts/build-client.mjs from index.html and client.js. Do not edit by hand.\n';
const kiwiOutput =
  `${banner}` +
  `export const peachHtml = ${JSON.stringify(peachHtml)};\n` +
  `export const mangoJs = ${JSON.stringify(mangoJs)};\n`;

// Write only when the content changed. `wrangler dev` watches this file and rebuilds when it is touched, so an
// unconditional write made the local server rebuild and restart about once a second, which also reset the world
// room (monsters barely patrolled and alarms never settled).
const generatedPath = join(clientDir, 'shell.generated.ts');
let previous = '';
try {
  previous = readFileSync(generatedPath, 'utf8');
} catch {
  previous = '';
}
if (previous !== kiwiOutput) {
  writeFileSync(generatedPath, kiwiOutput);
}
