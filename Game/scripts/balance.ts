// Balance study. Reproducible: `npm run balance` rewrites docs/balance-tables.md from the rules module alone.
// It calls the same rule functions the server uses (src/rules) through the deterministic sim (src/sim/sim.ts).
// Seeds only choose the order of actions that fall due in the same 100 ms tick, so results are exact, not sampled.

import { writeFileSync } from 'node:fs';
import {
  COIN_LIFETIME_DAYS,
  duelMaxHealth,
  duelPayout,
  duelStrike,
  mangoGearRows,
  maxHealth,
  onionMonsterRows,
  papayaLevelRows,
  pearTimings,
  type Hero,
} from '../src/rules';
import { duel, hunt, startingHero } from '../src/sim/sim';

const SEEDS = Array.from({ length: 20 }, (_, i) => i + 1);
const swords = [null, 'shortSword', 'longSword', 'greatSword'] as const;
const armors = [null, 'leather', 'chain', 'plate'] as const;
const price = (id: string | null) => (id === null ? 0 : mangoGearRows.find((g) => g.id === id)!.price);
// Time per kill that the fight sim does not model: picking up the coin (rules: 2.25 s) plus walking to the next monster.
// The walk is an ASSUMPTION (3 s); section 5 shows how the result moves with 0 s, the default and 15 s.
const OVERHEAD_MS = pearTimings.coinPickupSeconds * 1000 + 3000;
const out: string[] = [];
const line = (s = '') => out.push(s);

function strikeOf(h: Hero): number {
  return papayaLevelRows.find((r) => r.level === h.level)!.strike + (h.sword === null ? 0 : mangoGearRows.find((g) => g.id === h.sword)!.amount);
}

line('# Balance tables (generated)');
line();
line('Generated by `npm run balance` (scripts/balance.ts). Do not edit by hand. All numbers come from `src/rules` through the deterministic sim.');
line(`Seeds 1..${SEEDS.length} only reorder same-tick actions. Player swing gap ${pearTimings.playerAttackGapSeconds} s, tick 100 ms.`);
line(`Per-kill overhead not modelled by the fight sim: ${OVERHEAD_MS / 1000} s (rules coin pickup ${pearTimings.coinPickupSeconds} s + an assumed 3 s walk).`);
line();

// Fight-to-the-death: one long hunt from full health.
function huntStand(hero: Hero, monsterId: string, seed: number) {
  return hunt({ hero, monsterId, kills: 60, seed, maxSeconds: 3600 });
}
// Retreat strategy: one monster at a time, heal to full at the fountain below 40% health, a death costs the fight only.
function huntRetreat(hero0: Hero, monsterId: string, seed: number, fights: number, overheadMs = OVERHEAD_MS) {
  let hero = hero0;
  let kills = 0, deaths = 0, ms = 0;
  for (let i = 0; i < fights; i++) {
    const r = hunt({ hero, monsterId, kills: 1, seed: seed + i, maxSeconds: 600 });
    ms += r.elapsedMs + (r.died ? 0 : overheadMs);
    if (r.died) { deaths++; hero = { ...hero0, coins: hero.coins }; continue; }
    kills++;
    hero = r.hero;
    if (hero.health < 0.4 * maxHealth(hero)) hero = { ...hero, health: maxHealth(hero) };
  }
  return { kills, deaths, ms, coins: hero.coins };
}

// 1. PvE by zone and build.
line('## 1. PvE: survival and income by zone and build');
line();
line('"Stand" = fight monsters back to back from full health with no retreat, kills until the first death (cap 60). "Retreat" = one monster at a time, heal to full at the town fountain below 40% health (the heal trip is assumed free and instant), 100 fights. Coins per minute include the pickup and walk overhead.');
line();
line('| zone | level | sword | armor | max HP | strike | kills before first death (stand) | retreat: kills / deaths per 100 fights | coins per minute (retreat) |');
line('|---|---|---|---|---|---|---|---|---|');
const builds: Array<[number, Hero['sword'], Hero['armor']]> = [
  [1, null, null], [1, 'shortSword', 'leather'], [3, null, null], [3, 'shortSword', 'leather'], [3, 'longSword', 'chain'],
  [5, 'longSword', 'chain'], [5, 'greatSword', 'plate'], [6, 'greatSword', 'plate'],
];
for (const row of onionMonsterRows) {
  for (const [level, sword, armor] of builds) {
    const hero = startingHero({ level, sword, armor, place: row.zone as Hero['place'] });
    let killsSum = 0, cpm = 0, rKills = 0, rDeaths = 0;
    for (const seed of SEEDS) {
      killsSum += huntStand(hero, row.id, seed).kills;
      const rr = huntRetreat(hero, row.id, seed * 100, 100);
      rKills += rr.kills; rDeaths += rr.deaths;
      cpm += (rr.coins / Math.max(1, rr.ms)) * 60000;
    }
    const n = SEEDS.length;
    line(`| ${row.zone} (${row.id}) | ${level} | ${sword ?? '-'} | ${armor ?? '-'} | ${maxHealth(hero)} | ${strikeOf(hero)} | ${(killsSum / n).toFixed(1)} | ${(rKills / n).toFixed(0)} / ${(rDeaths / n).toFixed(1)} | ${(cpm / n).toFixed(1)} |`);
  }
}
line();

// 2. Economy.
line('## 2. Economy: coin income and time to afford gear');
line();
line('Retreat strategy, 100 fights per seed, each build in a zone it can handle. Includes the rules coin pickup plus the assumed walk; fountain trips are free and instant here.');
line();
line(`| zone | build | coins per minute | minutes to afford short sword + leather (${price('shortSword') + price('leather')} coins) | minutes to afford great sword + plate (${price('greatSword') + price('plate')} coins) |`);
line('|---|---|---|---|---|');
const econ: Array<[string, number, Hero['sword'], Hero['armor']]> = [
  ['wolf', 1, null, null], ['wolf', 3, 'shortSword', 'leather'], ['bear', 3, 'longSword', 'chain'], ['bear', 5, 'longSword', 'chain'],
  ['skeleton', 5, 'greatSword', 'plate'], ['skeleton', 6, 'greatSword', 'plate'],
];
function cpmOf(mid: string, level: number, sword: Hero['sword'], armor: Hero['armor']): number {
  const row = onionMonsterRows.find((r) => r.id === mid)!;
  const hero = startingHero({ level, sword, armor, place: row.zone as Hero['place'] });
  let c = 0;
  for (const seed of SEEDS) { const rr = huntRetreat(hero, mid, seed * 100, 100); c += (rr.coins / Math.max(1, rr.ms)) * 60000; }
  return c / SEEDS.length;
}
for (const [mid, level, sword, armor] of econ) {
  const row = onionMonsterRows.find((r) => r.id === mid)!;
  const cpm = cpmOf(mid, level, sword, armor);
  line(`| ${row.zone} (${mid}) | L${level} ${sword ?? '-'}/${armor ?? '-'} | ${cpm.toFixed(1)} | ${((price('shortSword') + price('leather')) / cpm).toFixed(1)} | ${((price('greatSword') + price('plate')) / cpm).toFixed(1)} |`);
}
line();
line(`Coins expire ${COIN_LIFETIME_DAYS} days after pickup and are spent oldest first. A player who spends what they earn loses nothing; coins held a full week are lost. The dearest single item costs ${Math.max(...mangoGearRows.map((g) => g.price))} coins, so expiry never blocks a purchase and only punishes pure hoarding.`);
line();

// 3. Duel matrix at the duel level.
line('## 3. Duels: all 16 gear builds against each other at duel level 3');
line();
const dl = papayaLevelRows.find((r) => r.level === 3)!;
line(`Both duelists fight with level 3 base stats (${dl.baseHp} HP, strike ${dl.strike}) plus their own sword and armor, whatever their real level. Armor does not reduce damage; it adds duel HP. Same swing gap, so the build that needs fewer swings wins; equal swings is decided by the same-tick order (the seed). Win rate of the row build against each of the other 15 builds, seeds 1..${SEEDS.length}.`);
line();
line('| build (sword / armor) | cost | duel HP | duel strike | swings to kill a bare duelist | average win rate vs the other 15 builds | win-rate points per coin |');
line('|---|---|---|---|---|---|---|');
type B = { sword: Hero['sword']; armor: Hero['armor'] };
const all: B[] = [];
for (const sword of swords) for (const armor of armors) all.push({ sword, armor });
const mk = (b: B, level = 3): Hero => startingHero({ level, sword: b.sword, armor: b.armor, coins: 20, place: 'green' });
const lbl = (b: B) => `${b.sword ?? '-'}/${b.armor ?? '-'}`;
const wr: number[][] = all.map(() => all.map(() => 0));
all.forEach((a, i) => all.forEach((b, j) => {
  if (i === j) return;
  let w = 0;
  for (const seed of SEEDS) if (duel({ first: mk(a), second: mk(b), seed }).winner === 'first') w++;
  wr[i]![j] = w / SEEDS.length;
}));
all.forEach((a, i) => {
  const h = mk(a);
  const others = wr[i]!.filter((_, j) => j !== i);
  const avg = others.reduce((x, y) => x + y, 0) / others.length;
  const cost = price(a.sword) + price(a.armor);
  const swings = Math.ceil(duelMaxHealth(mk({ sword: null, armor: null })) / duelStrike(h));
  line(`| ${a.sword ?? '-'} / ${a.armor ?? '-'} | ${cost} | ${duelMaxHealth(h)} | ${duelStrike(h)} | ${swings} | ${(avg * 100).toFixed(0)}% | ${cost === 0 ? 'n/a' : ((avg * 100) / cost).toFixed(2)} |`);
});
line();
const dominated: string[] = [];
all.forEach((a, i) => all.forEach((b, j) => {
  if (i === j) return;
  if (wr[i]![j] === 1 && price(a.sword) + price(a.armor) <= price(b.sword) + price(b.armor)) dominated.push(`${lbl(a)} beats ${lbl(b)} in every seed at equal or lower cost`);
}));
line(`Builds that beat another build in every seed at equal or lower price: ${dominated.length === 0 ? 'none' : dominated.length}.`);
for (const s of dominated) line(`- ${s}`);
line();
let cycles = 0; const cycleEx: string[] = [];
for (let i = 0; i < all.length; i++) for (let j = 0; j < all.length; j++) for (let k = 0; k < all.length; k++) {
  if (i < j && i < k && wr[i]![j]! >= 0.95 && wr[j]![k]! >= 0.95 && wr[k]![i]! >= 0.95) { cycles++; if (cycleEx.length < 3) cycleEx.push(`${lbl(all[i]!)} > ${lbl(all[j]!)} > ${lbl(all[k]!)} > ${lbl(all[i]!)}`); }
}
line(`Rock-paper-scissors cycles among builds (each link a win rate of 95% or more): ${cycles}${cycleEx.length ? ` (e.g. ${cycleEx.join('; ')})` : ''}.`);
line();
const same = (level: number) => { let w = 0; for (const s of SEEDS) if (duel({ first: mk({ sword: 'longSword', armor: 'chain' }, level), second: mk({ sword: 'longSword', armor: 'chain' }, 3), seed: s }).winner === 'first') w++; return w / SEEDS.length; };
line(`Real level no longer matters in a duel: a level 1, 3 and 6 character with the same long sword and chain mail beat an identical level 3 opponent ${(same(1) * 100).toFixed(0)}%, ${(same(3) * 100).toFixed(0)}% and ${(same(6) * 100).toFixed(0)}% of the time. The stats are identical, so only the tie-break decides; the number is the tie-break, not a skill edge.`);
line();

// 4. PvP and PvE together.
line('## 4. PvP and PvE together: what a duel is worth');
line();
line('Payout is half of the loser\'s purse, rounded down. Each payout is compared with the farming income of a mid build (level 3, short sword + leather, wolves) and a top build (level 6, great sword + plate, skeletons).');
line();
const wolfCpm = cpmOf('wolf', 3, 'shortSword', 'leather');
const skelCpm = cpmOf('skeleton', 6, 'greatSword', 'plate');
line(`Income used: wolves ${wolfCpm.toFixed(1)} coins/min, skeletons ${skelCpm.toFixed(1)} coins/min.`);
line();
line('| loser purse | payout to winner | equals minutes of wolf farming | equals minutes of skeleton farming |');
line('|---|---|---|---|');
for (const purse of [500, 2000, 5000, 10000]) {
  const p = duelPayout(purse);
  line(`| ${purse} | ${p} | ${(p / wolfCpm).toFixed(1)} | ${(p / skelCpm).toFixed(1)} |`);
}
line();

// 5. Sustained play.
line('## 5. Sustained play: levels and gear from a fresh character');
line();
line('Greedy policy with the retreat strategy: hunt wolves below level 3, bears at levels 3-4, skeletons from level 5, and buy the best affordable upgrade as soon as it is on offer. Minutes of play to reach each milestone (average of 10 seeded runs) for three per-kill overheads (coin pickup and walking). The middle column is the rules pickup plus the assumed walk.');
line();
function sustained(seed: number, overheadMs: number) {
  let hero: Hero = startingHero({ place: 'green' });
  let ms = 0;
  const marks: Record<string, number> = {};
  const note = (k: string) => { if (marks[k] === undefined) marks[k] = ms / 60000; };
  const buy = () => {
    const tiers: Array<['sword' | 'armor', string]> = [['sword', 'greatSword'], ['sword', 'longSword'], ['sword', 'shortSword'], ['armor', 'plate'], ['armor', 'chain'], ['armor', 'leather']];
    for (const [slot, id] of tiers) {
      const cur = slot === 'sword' ? hero.sword : hero.armor;
      const order = slot === 'sword' ? ['shortSword', 'longSword', 'greatSword'] : ['leather', 'chain', 'plate'];
      if (cur !== null && order.indexOf(cur) >= order.indexOf(id)) continue;
      const p = price(id);
      if (hero.coins >= p) { hero = { ...hero, coins: hero.coins - p, [slot]: id } as Hero; note(`bought ${id}`); return; }
    }
  };
  for (let fight = 0; fight < 20000 && ms < 8 * 3600_000; fight++) {
    const zone = hero.level >= 5 ? 'skeleton' : hero.level >= 3 ? 'bear' : 'wolf';
    const r = hunt({ hero, monsterId: zone, kills: 1, seed: seed + fight, maxSeconds: 600 });
    ms += r.elapsedMs + (r.died ? 0 : overheadMs);
    if (r.died) { hero = { ...hero, health: maxHealth(hero) }; continue; }
    hero = r.hero;
    if (hero.health < 0.4 * maxHealth(hero)) hero = { ...hero, health: maxHealth(hero) };
    note(`level ${hero.level}`);
    buy();
  }
  return marks;
}
const keys = ['level 2', 'level 3', 'level 4', 'level 5', 'level 6', 'bought shortSword', 'bought leather', 'bought longSword', 'bought chain', 'bought greatSword', 'bought plate'];
const overheads = [0, OVERHEAD_MS, 15000];
const avg: Record<number, Record<string, string>> = {};
for (const oh of overheads) {
  const agg: Record<string, number[]> = {};
  for (const seed of SEEDS.slice(0, 10)) { const m = sustained(seed * 1000, oh); for (const k of keys) if (m[k] !== undefined) (agg[k] ??= []).push(m[k]!); }
  avg[oh] = {};
  for (const k of keys) avg[oh]![k] = agg[k] ? `${(agg[k]!.reduce((a, b) => a + b, 0) / agg[k]!.length).toFixed(1)}${agg[k]!.length < 10 ? ` (${agg[k]!.length}/10 runs)` : ''}` : 'not reached';
}
line(`| milestone | ${overheads.map((o) => `${(o / 1000).toFixed(2)} s per kill`).join(' | ')} |`);
line(`|---|${overheads.map(() => '---').join('|')}|`);
for (const k of keys) line(`| ${k} | ${overheads.map((o) => avg[o]![k]).join(' | ')} |`);
line();

writeFileSync('docs/balance-tables.md', out.join('\n') + '\n');
console.log(`wrote docs/balance-tables.md (${out.length} lines)`);
